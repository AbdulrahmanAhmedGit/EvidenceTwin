 await expect(question).toHaveCSS('unicode-bidi','plaintext')
 await page.getByRole('button',{name:'Start Investigation',exact:true}).click()
 await expect(page).toHaveURL('/app/analyses/new?prepare=1')
 await expect(page.getByText('Local preparation only. Nothing has been uploaded or submitted.')).toBeVisible()
