test('planned XLSX stays local through the handoff while current CSV preparation remains intact',async({page})=>{
 const mutations:string[]=[]
 page.on('request',request=>{if(request.method()!=='GET')mutations.push(request.url())})
 await page.goto('/app/analyses/new')
 await page.getByRole('textbox',{name:'Scientific claim or research question'}).fill('Does the source support the reported change?')
 await page.getByLabel('Attach evidence files').setInputFiles([{name:'data.csv',mimeType:'text/csv',buffer:Buffer.from('value\n20')},{name:'planned.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from('Authored frontend test bytes')}])
 await page.getByRole('button',{name:'Start Investigation',exact:true}).click()
 await expect(page.locator('.planned-evidence-note')).toContainText('planned.xlsx')
 await expect(page.locator('.file')).toContainText('data.csv')
 await expect(page.locator('.file')).not.toContainText('planned.xlsx')
 await page.getByRole('link',{name:'Edit research question'}).click()
 await expect(page.getByRole('list',{name:'Selected evidence'})).toContainText('planned.xlsx')
 expect(mutations).toEqual([])
})

