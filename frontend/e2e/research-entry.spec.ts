test('changing or removing an educational case stays in preparation and preserves the question',async({page})=>{
 await page.goto('/app/analyses/new')
 await page.getByRole('textbox',{name:'Scientific claim or research question'}).fill('Keep this question while changing evidence.')
 await page.getByRole('button',{name:'Start Investigation',exact:true}).click()
 const caseSelect=page.getByLabel('Educational case (optional)',{exact:true})
 await caseSelect.selectOption('a1')
 await expect(page).toHaveURL('/app/analyses/new?prepare=1')
 await expect(caseSelect).toHaveValue('a1')
 await caseSelect.selectOption('a2')
 await expect(page.getByRole('heading',{name:'Evidence',exact:true})).toBeVisible()
 await expect(caseSelect).toHaveValue('a2')
 await caseSelect.selectOption('')
 await expect(caseSelect).toHaveValue('')
 await expect(page.getByRole('button',{name:'Continue',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Edit research question'}).click()
 await expect(page.getByRole('textbox',{name:'Scientific claim or research question'})).toHaveValue('Keep this question while changing evidence.')
})
